export function statusNote(state: {
  web?: boolean;
  phase: string;
  questions_asked: number;
  question_budget: number;
  dimensions: { id: string; name: string; status: string; level: string; impact: number }[];
  funnel?: { final: number; ratio: number };
  backtest?: { agreement: number };
  meta?: { job: { title: string }; generated: boolean; jd_source?: string };
}) {
  const dims = state.dimensions.map((d) => `${d.id}:${d.name}[${d.status}/${d.level}/影响${d.impact}]`).join("；");
  return `[当前状态] 阶段：${state.phase}；联网搜索：${state.web ? "可用（智谱，真实网页）" : "不可用"}；` +
    (state.meta ? `岗位：${state.meta.job.title}（${state.meta.generated ? "按岗位生成的模拟数据" : "预置数据"}）；JD 来源：${state.meta.jd_source ?? "公司模板"}；` : "尚未加载岗位数据；") +
    `已提问 ${state.questions_asked}/${state.question_budget}；` +
    (state.funnel && dims ? `漏斗剩余 ${state.funnel.final} 人（${state.funnel.ratio}%）；` : "") +
    (state.backtest && dims ? `回测一致率 ${state.backtest.agreement}%；` : "") +
    (dims ? `维度：${dims}` : "画像尚未初始化");
}

