- 「能力与背景」：背景类型、关键技能深度、行业经验（优先级取舍，「只能保一个保哪个」）
- 「工作方式」：节奏、管理、合规改写（合规项选项给出合规改写）
校准已经回答清楚的维度（经理的选择和口述一致）不必再问，直接写回并在消息里一句话说明。
